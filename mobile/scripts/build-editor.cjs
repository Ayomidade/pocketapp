const esbuild = require('esbuild');
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const result = esbuild.buildSync({ entryPoints: [path.join(root, 'src/features/editor/webEditor.js')], bundle: true, write: false, format: 'iife', platform: 'browser', target: 'es2020', minify: true });
fs.writeFileSync(path.join(root, 'src/features/editor/editorBundle.js'), `// Generated by npm run build:editor.\nexport default ${JSON.stringify(result.outputFiles[0].text)};\n`);
